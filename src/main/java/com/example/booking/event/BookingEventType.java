package com.example.booking.event;

/**
 * Единый топик booking-events для всех событий агрегата Booking (а не
 * отдельный топик на каждый тип события) — это осознанный выбор:
 * события об одной и той же брони, отправленные с partition-key = bookingId,
 * всегда попадают в одну и ту же партицию и, соответственно, сохраняют
 * порядок друг относительно друга (Kafka гарантирует порядок только внутри
 * партиции). Если бы CONFIRMED и CANCELLED летели в разные топики, порядок
 * между ними для одного bookingId ничем бы не гарантировался — консьюмер
 * теоретически мог бы обработать "cancelled" раньше "confirmed".
 * Разделение на типы делаем полем eventType внутри одного события,
 * а не топиком — консьюмеры фильтруют по типу на своей стороне.
 */
public enum BookingEventType {
    CONFIRMED,
    CANCELLED
}